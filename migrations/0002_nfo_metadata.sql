-- Persist normalized local NFO metadata without treating the sidecar XML as
-- the public contract. Local values coexist with provider-owned values and
-- survive remote metadata refreshes.

alter table media_items
    add column if not exists tagline text,
    add column if not exists premiere_date date,
    add column if not exists content_rating text;

alter table media_item_external_ids
    add column if not exists retrieved_via varchar(32) not null default 'tmdb';

alter table media_item_external_ids
    drop constraint if exists media_item_external_ids_pkey;

alter table media_item_external_ids
    add constraint media_item_external_ids_pkey
        primary key (media_item_id, provider, retrieved_via),
    add constraint media_item_external_ids_retrieved_via_format
        check (retrieved_via ~ '^[a-z0-9][a-z0-9_]*$');

alter table media_item_ratings
    drop constraint if exists media_item_ratings_media_item_id_source_kind_key;

alter table media_item_ratings
    add constraint media_item_ratings_media_item_source_kind_via_key
        unique (media_item_id, source, kind, retrieved_via),
    add constraint media_item_ratings_retrieved_via_format
        check (retrieved_via ~ '^[a-z0-9][a-z0-9_]*$');

create table if not exists media_local_metadata_sources (
    id bigint generated by default as identity primary key,
    library_id bigint not null references libraries(id) on delete cascade,
    media_item_id bigint not null,
    source_path text not null,
    document_type varchar(32) not null,
    target_media_type varchar(32)
        generated always as (
            case document_type
                when 'movie' then 'movie'::varchar(32)
                when 'tvshow' then 'series'::varchar(32)
                when 'episodedetails' then 'episode'::varchar(32)
                else null::varchar(32)
            end
        ) stored,
    schema_version integer not null default 1,
    is_locked boolean not null default false,
    is_selected boolean not null default false,
    payload jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (library_id, source_path),
    unique (id, media_item_id),
    check (btrim(source_path) <> ''),
    check (document_type in ('movie', 'tvshow', 'episodedetails')),
    check (schema_version > 0),
    check (jsonb_typeof(payload) = 'object'),
    foreign key (media_item_id, library_id, target_media_type)
        references media_items(id, library_id, media_type)
        on delete cascade
);

create index if not exists idx_media_local_metadata_sources_media_item
    on media_local_metadata_sources(media_item_id);

create unique index if not exists idx_media_local_metadata_sources_selected_media_item
    on media_local_metadata_sources(media_item_id)
    where is_selected;

alter table media_item_external_ids
